//! Seeds: the build environments taken from outside, pinned by digest (a target's `[seed]`).
//!
//! A seed is a base image, optionally with other images copied over it (`layers`). dust-builder
//! generates its Containerfile; the seed's key is that Containerfile's digest. StageX bootstraps
//! everything else: its GCC builds the bootstrap LLVM, which builds musl, the LLVM runtimes and
//! the system everything else builds on.

use std::fmt::Write as _;

use anyhow::ensure;
use serde::Deserialize;

use crate::recipe::ComponentName;
use crate::sha256::Sha256;

/// The seed of a target, named after it.
#[derive(Debug)]
pub struct Seed {
    pub name: ComponentName,
    /// Its pinned images: the base, then the layers.
    pub images: Vec<String>,
    pub containerfile: String,
}

/// A target's `[seed]`.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct File {
    base: String,
    #[serde(default)]
    layers: Vec<String>,
}

impl Seed {
    pub fn new(name: ComponentName, file: &File) -> anyhow::Result<Self> {
        let images: Vec<String> = std::iter::once(&file.base).chain(&file.layers).cloned().collect();
        for image in &images {
            ensure!(
                pinned(image),
                "{image} is not pinned by digest (`<name>@sha256:<digest>`)"
            );
        }
        let containerfile = containerfile(&name, file);
        Ok(Self {
            name,
            images,
            containerfile,
        })
    }

    /// What its image is built from, part of the key of every environment on it.
    pub fn key(&self) -> Sha256 {
        Sha256::digest(&self.containerfile)
    }
}

/// `name@sha256:<64 hex digits>`.
fn pinned(image: &str) -> bool {
    image.split_once("@sha256:").is_some_and(|(name, digest)| {
        !name.is_empty() && digest.len() == 64 && digest.bytes().all(|b| b.is_ascii_hexdigit())
    })
}

fn containerfile(name: &ComponentName, file: &File) -> String {
    let mut text = format!("# Generated by dust-builder from the seed of target {name}.\n");
    for (i, layer) in file.layers.iter().enumerate() {
        let _ = writeln!(text, "FROM {layer} AS layer-{i}");
    }
    let _ = writeln!(text, "FROM {}", file.base);
    for i in 0..file.layers.len() {
        let _ = writeln!(text, "COPY --from=layer-{i} / /");
    }
    text.push_str("ENTRYPOINT []\nWORKDIR /work\n");
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    const DIGEST: &str = "7d9bad63fafe72a3934a6efea9f742bf3a610a169bd401533a2b57c45efa2f2d";

    fn parse(text: &str) -> anyhow::Result<Seed> {
        Seed::new("base".parse().unwrap(), &toml::from_str(text)?)
    }

    #[test]
    fn generates_the_containerfile() {
        let seed = parse(&format!(
            "base = \"example.org/base@sha256:{DIGEST}\"\n\
                 layers = [\"example.org/a@sha256:{DIGEST}\", \"example.org/b@sha256:{DIGEST}\"]\n"
        ))
        .unwrap();
        assert_eq!(
            seed.containerfile,
            format!(
                "# Generated by dust-builder from the seed of target base.\n\
                 FROM example.org/a@sha256:{DIGEST} AS layer-0\n\
                 FROM example.org/b@sha256:{DIGEST} AS layer-1\n\
                 FROM example.org/base@sha256:{DIGEST}\n\
                 COPY --from=layer-0 / /\n\
                 COPY --from=layer-1 / /\n\
                 ENTRYPOINT []\n\
                 WORKDIR /work\n"
            )
        );
        assert_eq!(seed.images.len(), 3);
    }

    #[test]
    fn rejects_invalid_seeds() {
        let base = format!("base = \"example.org/base@sha256:{DIGEST}\"\n");
        for (text, why) in [
            ("base = \"example.org/base:latest\"\n".to_owned(), "unpinned"),
            (format!("{base}layer = []\n"), "unknown field"),
        ] {
            assert!(parse(&text).is_err(), "{why}");
        }
    }
}
