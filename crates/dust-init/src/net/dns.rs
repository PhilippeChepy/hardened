//! `/run/hardened/{resolv.conf,hosts}` rendering.

use std::fs;
use std::io::{self, Write};
use std::net::IpAddr;
use std::os::unix::fs::OpenOptionsExt;
use std::path::Path;

use crate::types::Hostname;

/// The resolver ignores nameservers past the third (glibc `MAXNS`, musl likewise).
const MAX_NAMESERVERS: usize = 3;
/// glibc `MAXDNSRCH`, for workloads on glibc.
const MAX_SEARCH_DOMAINS: usize = 6;
/// musl (dust-init's resolver) ignores a `search` line whose domains, with the line feed, do not
/// fit in 256 bytes.
const MAX_SEARCH_LENGTH: usize = 254;

/// Renders `resolv.conf`. Nameservers and domains are deduplicated, keeping the first occurrence.
pub fn render_resolv_conf(nameservers: &[IpAddr], search: &[String]) -> String {
    let mut out = String::from("# Generated by dust-init.\n");
    for server in dedup(nameservers.iter()).take(MAX_NAMESERVERS) {
        out.push_str(&format!("nameserver {server}\n"));
    }
    let mut length = 0;
    let search: Vec<_> = dedup(search.iter())
        .take(MAX_SEARCH_DOMAINS)
        .map(String::as_str)
        .take_while(|domain| {
            length += domain.len() + usize::from(length > 0);
            length <= MAX_SEARCH_LENGTH
        })
        .collect();
    if !search.is_empty() {
        out.push_str(&format!("search {}\n", search.join(" ")));
    }
    out
}

/// Renders `hosts`, mapping `hostname` (and its first label when it is qualified) to `127.0.1.1`
/// as Debian does, so that it resolves without DNS whatever the interface addresses.
pub fn render_hosts(hostname: &Hostname) -> String {
    let short = hostname.short();
    let names = if short == hostname.as_str() {
        short.to_owned()
    } else {
        format!("{hostname} {short}")
    };
    format!(
        "# Generated by dust-init.\n\
         127.0.0.1\tlocalhost\n\
         127.0.1.1\t{names}\n\
         ::1\tlocalhost ip6-localhost ip6-loopback\n\
         ff02::1\tip6-allnodes\n\
         ff02::2\tip6-allrouters\n"
    )
}

/// Replaces `dir/name` atomically (temporary file + rename), creating `dir` if needed, so that
/// readers never see a partial file.
pub fn write_atomic(dir: &Path, name: &str, contents: &str) -> io::Result<()> {
    fs::create_dir_all(dir)?;
    let tmp = dir.join(format!(".{name}.tmp"));
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o644)
        .open(&tmp)?;
    file.write_all(contents.as_bytes())?;
    file.sync_all()?;
    fs::rename(&tmp, dir.join(name))
}

fn dedup<'a, T: PartialEq + 'a>(items: impl Iterator<Item = &'a T>) -> impl Iterator<Item = &'a T> {
    let mut seen = Vec::new();
    items.filter(move |item| {
        let new = !seen.contains(item);
        if new {
            seen.push(*item);
        }
        new
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolv_conf() {
        let servers: Vec<IpAddr> = ["10.0.0.2", "10.0.0.3", "10.0.0.2", "2001:db8::53", "10.0.0.4"]
            .map(|s| s.parse().unwrap())
            .into();
        let search = ["a.internal", "b.internal", "a.internal"].map(String::from);
        assert_eq!(
            render_resolv_conf(&servers, &search),
            "# Generated by dust-init.\n\
             nameserver 10.0.0.2\n\
             nameserver 10.0.0.3\n\
             nameserver 2001:db8::53\n\
             search a.internal b.internal\n"
        );
        assert_eq!(render_resolv_conf(&[], &[]), "# Generated by dust-init.\n");
    }

    #[test]
    fn search_line_fits_musl() {
        // Domains of 114 characters: two fit (229), three do not (344).
        let domain = |c: char| format!("{}.{}", c.to_string().repeat(63), "x".repeat(50));
        let search = [domain('a'), domain('b'), domain('c')];
        let conf = render_resolv_conf(&[], &search);
        let line = conf.lines().find(|l| l.starts_with("search ")).unwrap();
        assert_eq!(line, format!("search {} {}", search[0], search[1]));
    }

    #[test]
    fn hosts() {
        let hosts = render_hosts(&"web-1.example.com".parse().unwrap());
        assert!(hosts.contains("127.0.0.1\tlocalhost\n"));
        assert!(hosts.contains("127.0.1.1\tweb-1.example.com web-1\n"));
        assert!(hosts.contains("::1\tlocalhost ip6-localhost ip6-loopback\n"));
        assert!(render_hosts(&"web-1".parse().unwrap()).contains("127.0.1.1\tweb-1\n"));
        // Injection through the hostname is impossible: such a name is not a `Hostname`.
        assert!("bad name\n127.0.0.1 evil".parse::<Hostname>().is_err());
    }

    #[test]
    fn writes_atomically() {
        let dir = tempfile::tempdir().unwrap();
        let sub = dir.path().join("run");
        write_atomic(&sub, "hosts", "one").unwrap();
        write_atomic(&sub, "hosts", "two").unwrap();
        assert_eq!(fs::read_to_string(sub.join("hosts")).unwrap(), "two");
        let entries: Vec<_> = fs::read_dir(&sub).unwrap().map(|e| e.unwrap().file_name()).collect();
        assert_eq!(entries, ["hosts"]);
    }
}
