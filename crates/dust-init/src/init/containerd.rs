//! The containerd daemon, supervised by dust-init: restarted with backoff whenever it exits.
//!
//! Its configuration is the image's, plus what user-data adds: the registry mirrors
//! (`hosts.toml` files under `config_path`) and credentials (the CRI plugin's `configs`), written
//! to `/run/containerd` before it starts.

use std::os::unix::fs::OpenOptionsExt;
use std::path::Path;

use anyhow::Context;
use tracing::error;

use crate::init::service::{self, Service, Spec};
use crate::process::Reaper;
use crate::settings::{self, RegistrySettings};

pub const SOCKET: &str = "/run/containerd/containerd.sock";
/// The image's configuration.
const BASE_CONFIG: &str = "/usr/share/hardened/containerd/config.toml";
/// What containerd runs with: the image's configuration and the registry credentials.
const CONFIG: &str = "/run/containerd/config.toml";
/// `config_path` of the CRI images and transfer plugins (in the image's configuration).
const HOSTS_DIR: &str = "/run/containerd/certs.d";
const LOG: &str = "/var/log/containerd.log";
const CRI_IMAGES: &str = "io.containerd.cri.v1.images";

/// Writes containerd's configuration for `registry`, then starts it. If the configuration cannot
/// be written, containerd starts with the image's, without mirrors or credentials.
pub fn start(reaper: Reaper, registry: &RegistrySettings) -> Service {
    let config = match configure(registry) {
        Ok(()) => CONFIG,
        Err(e) => {
            error!("cannot apply settings.container-registry, containerd runs without it: {e:#}");
            BASE_CONFIG
        }
    };
    let spec = Spec {
        name: "containerd",
        program: "/usr/bin/containerd",
        args: vec!["--config".into(), config.into()],
        log: LOG,
    };
    Service::start(reaper, spec)
}

fn configure(registry: &RegistrySettings) -> anyhow::Result<()> {
    for (directory, hosts) in settings::hosts_files(registry) {
        let dir = Path::new(HOSTS_DIR).join(directory);
        std::fs::create_dir_all(&dir).with_context(|| dir.display().to_string())?;
        std::fs::write(dir.join("hosts.toml"), hosts).with_context(|| dir.display().to_string())?;
    }
    let base = std::fs::read_to_string(BASE_CONFIG).context(BASE_CONFIG)?;
    let config = with_credentials(&base, settings::cri_auth_configs(registry))?;
    // It holds the registry credentials.
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(CONFIG)
        .context(CONFIG)?;
    std::io::Write::write_all(&mut file, config.as_bytes()).context(CONFIG)
}

/// `base` with the CRI plugin's registry `configs` (credentials, by host) set to `configs`.
///
/// `configs` is deprecated in containerd 2 (until 2.7) in favor of `config_path`, whose
/// `hosts.toml` holds no credentials: it remains the way to give credentials to every CRI pull
/// that carries none.
fn with_credentials(base: &str, configs: toml::Table) -> anyhow::Result<String> {
    let mut config: toml::Table = base.parse().context("parsing the image's containerd configuration")?;
    if !configs.is_empty() {
        let registry = config
            .entry("plugins")
            .or_insert_with(|| toml::Table::new().into())
            .as_table_mut()
            .and_then(|plugins| {
                plugins
                    .entry(CRI_IMAGES)
                    .or_insert_with(|| toml::Table::new().into())
                    .as_table_mut()
            })
            .and_then(|images| {
                images
                    .entry("registry")
                    .or_insert_with(|| toml::Table::new().into())
                    .as_table_mut()
            })
            .context("the image's containerd configuration has no CRI registry table")?;
        registry.insert("configs".into(), configs.into());
    }
    Ok(format!(
        "# Generated by dust-init from {BASE_CONFIG} and settings.container-registry.\n{config}"
    ))
}

/// Copies the last `lines` lines of containerd's log to dust-init's log (and so the console).
pub fn log_tail(lines: usize) {
    service::log_tail("containerd", LOG, lines);
}

#[cfg(test)]
mod tests {
    use super::*;

    const BASE: &str = r#"version = 3
root = "/var/lib/containerd"

[plugins.'io.containerd.cri.v1.images']
  snapshotter = "overlayfs"

  [plugins.'io.containerd.cri.v1.images'.registry]
    config_path = "/run/containerd/certs.d"

[plugins.'io.containerd.cri.v1.runtime']
  enable_selinux = false
"#;

    #[test]
    fn credentials_are_added_to_the_cri_registry() {
        let registry: RegistrySettings =
            toml::from_str("[[credentials]]\nregistry = \"docker.io\"\nusername = \"me\"\npassword = \"hunter2\"\n")
                .unwrap();
        let config: toml::Table = with_credentials(BASE, settings::cri_auth_configs(&registry))
            .unwrap()
            .parse()
            .unwrap();
        let registry = &config["plugins"][CRI_IMAGES]["registry"];
        assert_eq!(registry["config_path"].as_str(), Some(HOSTS_DIR));
        let auth = &registry["configs"]["registry-1.docker.io"]["auth"];
        assert_eq!(
            (auth["username"].as_str(), auth["password"].as_str()),
            (Some("me"), Some("hunter2"))
        );
        assert_eq!(config["version"].as_integer(), Some(3));
        assert_eq!(
            config["plugins"]["io.containerd.cri.v1.runtime"]["enable_selinux"].as_bool(),
            Some(false)
        );
    }

    #[test]
    fn without_credentials_the_configuration_is_the_image_s() {
        let config: toml::Table = with_credentials(BASE, toml::Table::new()).unwrap().parse().unwrap();
        assert_eq!(config, BASE.parse::<toml::Table>().unwrap());
    }
}
