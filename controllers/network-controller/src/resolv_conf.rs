//! `resolv.conf` rendering.

use std::net::IpAddr;

use controllers_helpers::DomainName;

/// The resolver ignores nameservers past the third (glibc `MAXNS`, musl likewise).
const MAX_NAMESERVERS: usize = 3;
/// glibc `MAXDNSRCH`, for workloads on glibc.
const MAX_SEARCH_DOMAINS: usize = 6;
/// musl (the resolver of hardened's programs) ignores a `search` line whose domains, with the
/// line feed, do not fit in 256 bytes.
const MAX_SEARCH_LENGTH: usize = 254;

/// Renders `resolv.conf`. Nameservers and domains are deduplicated, keeping the first
/// occurrence.
#[must_use]
pub fn render(nameservers: &[IpAddr], search: &[DomainName]) -> String {
    let mut out = String::from("# Generated by network-controller.\n");
    for server in dedup(nameservers).into_iter().take(MAX_NAMESERVERS) {
        out.push_str(&format!("nameserver {server}\n"));
    }
    let mut domains = String::new();
    for domain in dedup(search).into_iter().take(MAX_SEARCH_DOMAINS) {
        let separator = usize::from(!domains.is_empty());
        if domains.len() + separator + domain.as_str().len() > MAX_SEARCH_LENGTH {
            break;
        }
        if separator == 1 {
            domains.push(' ');
        }
        domains.push_str(domain.as_str());
    }
    if !domains.is_empty() {
        out.push_str(&format!("search {domains}\n"));
    }
    out
}

#[must_use]
fn dedup<T: PartialEq>(items: &[T]) -> Vec<&T> {
    let mut unique = Vec::new();
    for item in items {
        if !unique.contains(&item) {
            unique.push(item);
        }
    }
    unique
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolv_conf() {
        let servers: Vec<IpAddr> = [
            "10.0.0.2",
            "10.0.0.3",
            "10.0.0.2",
            "2001:db8::53",
            "10.0.0.4",
        ]
        .map(|s| s.parse().unwrap())
        .into();
        let search = ["a.internal", "b.internal", "a.internal"].map(|d| d.parse().unwrap());
        assert_eq!(
            render(&servers, &search),
            "# Generated by network-controller.\n\
             nameserver 10.0.0.2\n\
             nameserver 10.0.0.3\n\
             nameserver 2001:db8::53\n\
             search a.internal b.internal\n"
        );
        assert_eq!(render(&[], &[]), "# Generated by network-controller.\n");
    }

    #[test]
    fn search_line_fits_musl() {
        // Domains of 114 characters: two fit (229), three do not (344).
        let domain = |c: char| {
            format!("{}.{}", c.to_string().repeat(63), "x".repeat(50))
                .parse::<DomainName>()
                .unwrap()
        };
        let search = [domain('a'), domain('b'), domain('c')];
        let conf = render(&[], &search);
        let line = conf.lines().find(|l| l.starts_with("search ")).unwrap();
        assert_eq!(line, format!("search {} {}", search[0], search[1]));
    }
}
