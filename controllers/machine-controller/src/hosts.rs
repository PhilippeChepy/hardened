//! The hostname: set in the kernel, and written to `/run/hardened/{hostname,hosts}`, which
//! `/etc/hostname` and `/etc/hosts` link to.

use std::fs;
use std::path::Path;

use anyhow::Context;
use controllers_helpers::Hostname;
use controllers_helpers::atomic_file;

use crate::hostnames;

/// Where `/etc/hostname` and `/etc/hosts` link to.
const DIR: &str = "/run/hardened";

/// Sets the kernel's hostname, and writes `hostname` and `hosts` to [`DIR`].
pub fn apply(hostname: &Hostname) -> anyhow::Result<()> {
    rustix::system::sethostname(hostname.as_str().as_bytes()).context("setting the hostname")?;
    let dir = Path::new(DIR);
    fs::create_dir_all(dir).context(DIR)?;
    for (name, contents) in [
        ("hostname", format!("{hostname}\n")),
        ("hosts", render(hostname)),
    ] {
        let path = dir.join(name);
        atomic_file::write(&path, contents.as_bytes(), 0o644)
            .with_context(|| path.display().to_string())?;
    }
    Ok(())
}

/// Renders `hosts`, mapping `hostname` (and its first label when it is qualified) to `127.0.1.1`
/// as Debian does, so that it resolves without DNS whatever the interface addresses.
#[must_use]
fn render(hostname: &Hostname) -> String {
    let short = hostnames::short(hostname);
    let names = if short == hostname.as_str() {
        short.to_owned()
    } else {
        format!("{hostname} {short}")
    };
    format!(
        "# Generated by machine-controller.\n\
         127.0.0.1\tlocalhost\n\
         127.0.1.1\t{names}\n\
         ::1\tlocalhost ip6-localhost ip6-loopback\n\
         ff02::1\tip6-allnodes\n\
         ff02::2\tip6-allrouters\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hosts() {
        let hosts = render(&"web-1.example.com".parse().unwrap());
        assert!(hosts.contains("127.0.0.1\tlocalhost\n"));
        assert!(hosts.contains("127.0.1.1\tweb-1.example.com web-1\n"));
        assert!(hosts.contains("::1\tlocalhost ip6-localhost ip6-loopback\n"));
        assert!(
            render(&"web-1".parse().unwrap()).contains("127.0.1.1\tweb-1\n"),
            "an unqualified hostname is listed once"
        );
    }
}
