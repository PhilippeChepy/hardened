//! Linux kernel (longterm), booted as a unified kernel image.
//!
//! Everything needed to boot on the supported platforms is built in. Modules are signed with the
//! persistent key of `build/keys/` (lockdown requires signatures) and, through LoadPin, only
//! loaded (like firmware) from the dm-verity root.

use crate::recipe::prelude::*;

pub const NAME: ComponentName = name!("kernel");
const VERSION: &str = "6.18.58";
const SRC: Source = source!(
    formatcp!("https://cdn.kernel.org/pub/linux/kernel/v6.x/linux-{VERSION}.tar.xz"),
    "069b19f9032c4dac8149ae4b6520c35debca0f42a9f6d52ee55ba6ca9b818013",
);
/// The kernel image booted by the UKI.
pub const IMAGE: Output = Output::new(NAME, "bzImage");
/// The final kernel configuration, for inspection.
pub const CONFIG: Output = Output::new(NAME, "config");
/// `uname -r`.
pub const RELEASE: Output = Output::new(NAME, "kernel.release");

pub struct Kernel;

impl Component for Kernel {
    fn meta(&self) -> Meta {
        Meta::new(
            NAME,
            VERSION,
            ComponentType::OperatingSystem,
            "Linux kernel (longterm), booted as a unified kernel image",
            "GPL-2.0-only WITH Linux-syscall-note",
            "https://www.kernel.org",
        )
        .purl(format!("pkg:generic/linux@{VERSION}"))
        .cpe(format!("cpe:2.3:o:linux:linux_kernel:{VERSION}:*:*:*:*:*:*:*"))
    }

    fn build(&self, b: &mut Build) -> anyhow::Result<()> {
        let tree = b.unpack(&SRC);
        // Fails the build if an option of the fragment does not end up in the final .config.
        b.kernel_config(&tree, "x86_64_defconfig", include_str!("config.fragment"));

        // The persistent key, instead of one generated by (and different at) every build.
        let key = b.secret(crate::keys::MODULES);
        b.install(&key, &tree.join("certs/hardened-modules.pem"), Mode::new(0o600));
        reproducible(b.make(&tree)).args(["-s", "bzImage", "modules"]).run();
        let release = b.output(&RELEASE);
        b.cmd("make").dir(&tree).args(["-s", "kernelrelease"]).capture(&release);

        // modules_install signs the modules (CONFIG_MODULE_SIG_ALL).
        let staged = b.work("modules");
        reproducible(b.cmd("make").dir(&tree))
            .args(["-s", "modules_install", "INSTALL_MOD_STRIP=1", "DEPMOD=/sbin/depmod"])
            .arg(Arg::from("INSTALL_MOD_PATH=").concat(&staged))
            .run();
        let modules = b.root("/usr/lib/modules");
        b.copy(&staged.join("lib/modules/*"), &modules);
        b.remove(&modules.join("*/build"));
        b.remove(&modules.join("*/source"));

        let image = b.output(&IMAGE);
        b.install(&tree.join("arch/x86/boot/bzImage"), &image, Mode::FILE);
        let config = b.output(&CONFIG);
        b.install(&tree.join(".config"), &config, Mode::FILE);
        Ok(())
    }
}

/// Pins the build metadata the kernel embeds, for reproducible output.
fn reproducible(cmd: Cmd<'_>) -> Cmd<'_> {
    cmd.env("KBUILD_BUILD_TIMESTAMP", Arg::from("@").concat(Arg::epoch()))
        .env("KBUILD_BUILD_USER", "hardened")
        .env("KBUILD_BUILD_HOST", "hardened")
}
