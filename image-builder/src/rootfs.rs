//! Root filesystem assembly.
//!
//! Component outputs are merged into one tree; every path must be owned by exactly one component
//! (directories may be shared). The result is checked before it is sealed with dm-verity:
//! - every ELF file is a static executable or a kernel module: no dynamic loader, no shared
//!   library, so nothing to resolve or preload at run time;
//! - nothing is setuid/setgid or world-writable.
//!
//! Executables are then stripped of their symbol tables and debug information
//! ([`unstripped`], run by image assembly), whatever their component's build left in them.

use std::collections::BTreeMap;
use std::fs::Permissions;
use std::os::unix::fs::{MetadataExt, PermissionsExt};
use std::path::Path;

use anyhow::{Context, bail, ensure};
use serde::Serialize;
use walkdir::WalkDir;

use crate::build::Built;
use crate::recipe::ComponentName;
use crate::sha256::Sha256;

/// Every path of the root filesystem and the component that provides it.
#[derive(Debug, Default, Serialize)]
pub struct Manifest {
    pub entries: BTreeMap<String, Entry>,
}

/// A path of the root filesystem; `mode` holds the permission bits (`st_mode & 0o7777`).
#[derive(Debug, Serialize)]
#[serde(tag = "type", rename_all = "lowercase")]
pub enum Entry {
    Dir {
        component: ComponentName,
        mode: u32,
    },
    File {
        component: ComponentName,
        mode: u32,
        size: u64,
        sha256: Sha256,
    },
    Symlink {
        component: ComponentName,
        target: String,
    },
}

impl Entry {
    pub fn component(&self) -> &ComponentName {
        match self {
            Self::Dir { component, .. }
            | Self::File { component, .. }
            | Self::Symlink { component, .. } => component,
        }
    }
}

impl Manifest {
    /// Adds a regular file (`0644`) generated by image-builder itself (a container image archive)
    /// to the root filesystem at `root`, owned by `component`. Its directory must already exist.
    pub fn add_generated(
        &mut self,
        root: &Path,
        path: &str,
        component: &ComponentName,
        contents: &[u8],
    ) -> anyhow::Result<()> {
        if let Some(existing) = self.entries.get(path) {
            bail!(
                "/{path} is provided by both {} and {component}",
                existing.component()
            );
        }
        if let Some((parent, _)) = path.rsplit_once('/') {
            ensure!(
                matches!(self.entries.get(parent), Some(Entry::Dir { .. })),
                "the directory of /{path} is not part of the root filesystem"
            );
        }
        let mode = 0o644;
        let target = root.join(path);
        std::fs::write(&target, contents)?;
        std::fs::set_permissions(&target, Permissions::from_mode(mode))?;
        self.entries.insert(
            path.to_owned(),
            Entry::File {
                component: component.clone(),
                mode,
                size: contents.len() as u64,
                sha256: Sha256::digest(contents),
            },
        );
        Ok(())
    }

    /// Updates the sizes and checksums of `paths` (regular files of `root`) after they changed.
    pub fn rehash(&mut self, root: &Path, paths: &[String]) -> anyhow::Result<()> {
        for path in paths {
            let Some(Entry::File { size, sha256, .. }) = self.entries.get_mut(path) else {
                bail!("/{path} is not a file of the root filesystem");
            };
            let file = root.join(path);
            *size = std::fs::metadata(&file)?.len();
            *sha256 = Sha256::of_file(&file)?;
        }
        Ok(())
    }
}

/// The executables of the root filesystem that still carry a symbol table or debug information,
/// by path: what image assembly strips. Kernel modules (relocatable, and signed) are left alone.
pub fn unstripped(root: &Path, manifest: &Manifest) -> anyhow::Result<Vec<String>> {
    let mut paths = Vec::new();
    for (path, entry) in &manifest.entries {
        if let Entry::File { .. } = entry {
            let bytes = std::fs::read(root.join(path))?;
            if is_unstripped(&bytes).with_context(|| format!("parsing /{path}"))? {
                paths.push(path.clone());
            }
        }
    }
    Ok(paths)
}

fn is_unstripped(bytes: &[u8]) -> anyhow::Result<bool> {
    use goblin::elf::header::{ET_DYN, ET_EXEC};
    if !bytes.starts_with(b"\x7fELF") {
        return Ok(false);
    }
    let elf = goblin::elf::Elf::parse(bytes)?;
    if ![ET_EXEC, ET_DYN].contains(&elf.header.e_type) {
        return Ok(false);
    }
    Ok(elf.section_headers.iter().any(|section| {
        elf.shdr_strtab
            .get_at(section.sh_name)
            .is_some_and(|name| name == ".symtab" || name.starts_with(".debug_"))
    }))
}

/// Merges the root outputs of `components` into `dest`, which is recreated.
pub fn assemble(components: &[&Built<'_>], dest: &Path) -> anyhow::Result<Manifest> {
    if dest.exists() {
        std::fs::remove_dir_all(dest)?;
    }
    std::fs::create_dir_all(dest)?;
    let mut manifest = Manifest::default();

    for built in components {
        let name = built.job.recipe.name();
        let root = built.root();
        for entry in WalkDir::new(&root).sort_by_file_name().min_depth(1) {
            let entry = entry?;
            let rel = entry.path().strip_prefix(&root)?;
            let key = rel.to_string_lossy().into_owned();
            let target = dest.join(rel);
            let file_type = entry.file_type();
            let mode = entry.metadata()?.mode() & 0o7777;

            if let Some(existing) = manifest.entries.get(&key) {
                if file_type.is_dir() && matches!(existing, Entry::Dir { .. }) {
                    continue;
                }
                bail!(
                    "/{key} is provided by both {} and {name}",
                    existing.component()
                );
            }

            let item = if file_type.is_symlink() {
                let link = std::fs::read_link(entry.path())?;
                std::os::unix::fs::symlink(&link, &target)?;
                Entry::Symlink {
                    component: name.clone(),
                    target: link.to_string_lossy().into_owned(),
                }
            } else if file_type.is_dir() {
                std::fs::create_dir(&target)?;
                std::fs::set_permissions(&target, Permissions::from_mode(mode))?;
                Entry::Dir {
                    component: name.clone(),
                    mode,
                }
            } else if file_type.is_file() {
                std::fs::copy(entry.path(), &target)?;
                std::fs::set_permissions(&target, Permissions::from_mode(mode))?;
                Entry::File {
                    component: name.clone(),
                    mode,
                    size: entry.metadata()?.len(),
                    sha256: Sha256::of_file(&target)?,
                }
            } else {
                bail!("/{key} ({name}): unsupported file type");
            };
            manifest.entries.insert(key, item);
        }
    }

    check_permissions(&manifest)?;
    check_static(dest, &manifest)?;
    Ok(manifest)
}

fn check_permissions(manifest: &Manifest) -> anyhow::Result<()> {
    let mut problems = Vec::new();
    for (path, entry) in &manifest.entries {
        let mode = match entry {
            // The sticky bit is fine on directories (e.g. /tmp).
            Entry::Dir { mode, .. } => mode & !0o1000,
            Entry::File { mode, .. } => *mode,
            Entry::Symlink { .. } => continue,
        };
        if mode & 0o6000 != 0 {
            problems.push(format!("/{path} is setuid/setgid ({mode:o})"));
        }
        if mode & 0o002 != 0 {
            problems.push(format!("/{path} is world-writable ({mode:o})"));
        }
    }
    ensure!(
        problems.is_empty(),
        "root filesystem permission check failed:\n  {}",
        problems.join("\n  ")
    );
    Ok(())
}

/// Why an ELF file is not a static executable or a kernel module, if it is not.
fn dynamic_linking(bytes: &[u8]) -> anyhow::Result<Option<String>> {
    if !bytes.starts_with(b"\x7fELF") {
        return Ok(None);
    }
    let elf = goblin::elf::Elf::parse(bytes)?;
    if let Some(interpreter) = elf.interpreter {
        return Ok(Some(format!(
            "dynamically linked (interpreter {interpreter})"
        )));
    }
    if !elf.libraries.is_empty() {
        return Ok(Some(format!(
            "needs shared libraries {}",
            elf.libraries.join(", ")
        )));
    }
    // A position-independent file without an interpreter: a static PIE (flagged as such by the
    // linker) or a shared library.
    let pie = elf
        .dynamic
        .as_ref()
        .is_some_and(|dynamic| dynamic.info.flags_1 & goblin::elf::dynamic::DF_1_PIE != 0);
    if elf.header.e_type == goblin::elf::header::ET_DYN && !pie {
        return Ok(Some("is a shared library".to_owned()));
    }
    Ok(None)
}

/// Every ELF file is a static executable or a kernel module: the image holds no dynamic loader
/// or shared library.
fn check_static(root: &Path, manifest: &Manifest) -> anyhow::Result<()> {
    let mut problems = Vec::new();
    for (path, entry) in &manifest.entries {
        if let Entry::File { .. } = entry {
            let bytes = std::fs::read(root.join(path))?;
            if let Some(problem) =
                dynamic_linking(&bytes).with_context(|| format!("parsing /{path}"))?
            {
                problems.push(format!("/{path} {problem}"));
            }
        }
    }
    ensure!(
        problems.is_empty(),
        "static linking check failed:\n  {}",
        problems.join("\n  ")
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_dynamic_binaries() {
        // The test binary itself is dynamically linked on Linux hosts.
        let exe = std::fs::read(std::env::current_exe().unwrap()).unwrap();
        assert!(
            dynamic_linking(&exe)
                .unwrap()
                .unwrap()
                .starts_with("dynamically linked")
        );
        assert_eq!(dynamic_linking(b"#!/bin/false\n").unwrap(), None);
    }

    #[test]
    fn finds_unstripped_executables() {
        // The test binary has its symbol table.
        let exe = std::fs::read(std::env::current_exe().unwrap()).unwrap();
        assert!(is_unstripped(&exe).unwrap());
        assert!(!is_unstripped(b"#!/bin/false\n").unwrap());
    }
}
